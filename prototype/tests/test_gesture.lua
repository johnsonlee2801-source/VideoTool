package.path = (assert(os.getenv("VT_SCRIPT_DIR"), "run via tests/run.sh")) .. "/?.lua;./?.lua;" .. package.path
local T = require "minitest"
local Fake = require "fake_io"
local G = require "gesture"

local D = G.defaults   -- hold 2.0, 20px/0.1x up to 3.0, then 10px/0.1x up to 6.0, deadzone 8, min 0.5, snap on, threshold 0.25

-- ---------------------------------------------------------------- speed_for_drag
T.test("S1 no drag gives hold_speed", function()
    T.near(G.speed_for_drag(0, D), 2.0)
end)
T.test("S2 drag inside deadzone (+8) still hold_speed", function()
    T.near(G.speed_for_drag(8, D), 2.0)
end)
T.test("S3 drag inside deadzone (-8) still hold_speed", function()
    T.near(G.speed_for_drag(-8, D), 2.0)
end)
T.test("S4 one step right: deadzone + 20px = +0.1", function()
    T.near(G.speed_for_drag(28, D), 2.1)
end)
T.test("S5 one step left: -(deadzone + 20px) = -0.1", function()
    T.near(G.speed_for_drag(-28, D), 1.9)
end)
T.test("S6 ten steps right (deadzone + 200px) reaches 3.0", function()
    T.near(G.speed_for_drag(208, D), 3.0)
end)
T.test("S7 far right clamps at max_speed 6.0", function()
    T.near(G.speed_for_drag(5000, D), 6.0)
end)
T.test("S8 far left clamps at min_speed", function()
    T.near(G.speed_for_drag(-5000, D), 0.5)
end)
T.test("S9 snap off gives continuous value", function()
    local o = G.options({ snap_tenths = 0 })
    T.near(G.speed_for_drag(18, o), 2.05)       -- (18-8)/20*0.1 = 0.05
end)
T.test("S10 snap on rounds to nearest tenth", function()
    T.near(G.speed_for_drag(18, D), 2.1)        -- 2.05 rounds up
    T.near(G.speed_for_drag(17, D), 2.0)        -- 2.045 rounds down
end)
T.test("S11 custom hold_speed is the drag origin", function()
    local o = G.options({ hold_speed = 1.5 })
    T.near(G.speed_for_drag(0, o), 1.5)
    T.near(G.speed_for_drag(28, o), 1.6)
end)
T.test("S12 speed is monotonic non-decreasing in dx", function()
    local prev = -math.huge
    for dx = -800, 800 do
        local s = G.speed_for_drag(dx, D)
        T.truthy(s >= prev - 1e-9, "dropped at dx=" .. dx .. " (" .. s .. " < " .. prev .. ")")
        prev = s
    end
end)
T.test("S13 result never leaves [min_speed, max_speed]", function()
    for dx = -100000, 100000, 997 do
        local s = G.speed_for_drag(dx, D)
        T.truthy(s >= 0.5 and s <= 6.0, "out of range at dx=" .. dx .. ": " .. s)
    end
end)

-- ---------------------------------------------------------------- options sanitising
T.test("O1 px_per_tenth <= 0 falls back to default instead of dividing by zero", function()
    local o = G.options({ px_per_tenth = 0 })
    T.eq(o.px_per_tenth, D.px_per_tenth)
    T.near(G.speed_for_drag(28, o), 2.1)
end)
T.test("O2 min_speed above max_speed is rejected, defaults kept", function()
    local o = G.options({ min_speed = 3.0, max_speed = 1.0 })
    T.eq(o.min_speed, D.min_speed)
    T.eq(o.max_speed, D.max_speed)
end)
T.test("O3 hold_speed outside [min,max] is clamped into range", function()
    local o = G.options({ hold_speed = 9.0 })
    T.near(o.hold_speed, D.max_speed)
end)
T.test("O4 options() does not mutate defaults", function()
    G.options({ hold_speed = 1.1, px_per_tenth = 10 })
    T.near(G.defaults.hold_speed, 2.0)
    T.eq(G.defaults.px_per_tenth, 20)
end)

-- ---------------------------------------------------------------- hold / drag machine
local function machine(opts, init)
    local f = Fake.new(init)
    local m = G.new(G.options(opts or {}), f:io())
    return m, f
end

T.test("M1 tap (release before threshold) toggles pause, never touches speed", function()
    local m, f = machine()
    m:on_down(0); m:on_tick(0.10); m:on_up(0.20)
    T.eq(f.toggle_count, 1)
    T.eq(f.set_speed_count, 0)
    T.eq(f.show_count, 0)
    T.eq(m:is_holding(), false)
end)
T.test("M2 hold past threshold sets hold_speed and shows OSD once", function()
    local m, f = machine()
    m:on_down(0); m:on_tick(0.30)
    T.eq(m:is_holding(), true)
    T.near(f.speed, 2.0)
    T.eq(f.set_speed_count, 1)
    T.eq(f.toggle_count, 0)
    T.eq(f.last_show.speed, 2.0)
    T.eq(f.last_show.dx, 0)
    T.eq(f.show_count, 1)
end)
T.test("M3 hold while paused unpauses", function()
    local m, f = machine(nil, { paused = true })
    m:on_down(0); m:on_tick(0.30)
    T.eq(f.paused, false)
end)
T.test("M4 hold while playing does not call set_pause", function()
    local m, f = machine()
    m:on_down(0); m:on_tick(0.30)
    for _, c in ipairs(f.calls) do T.truthy(c[1] ~= "set_pause", "unexpected set_pause") end
end)
T.test("M5 drag right 80px gives 2.4", function()
    local m, f = machine(nil, { x = 500 })
    m:on_down(0); m:on_tick(0.30)
    f.x = 580; m:on_tick(0.35)
    T.near(f.speed, 2.4)
    T.eq(f.last_show.dx, 80)
end)
T.test("M6 drag far left clamps to min_speed", function()
    local m, f = machine(nil, { x = 2000 })
    m:on_down(0); m:on_tick(0.30)
    f.x = 0; m:on_tick(0.35)
    T.near(f.speed, 0.5)
end)
T.test("M7 release restores the pre-hold speed and hides OSD", function()
    local m, f = machine(nil, { speed = 1.25 })
    m:on_down(0); m:on_tick(0.30)
    f.x = f.x + 200; m:on_tick(0.40)
    m:on_up(0.50)
    T.near(f.speed, 1.25)
    T.eq(f.hide_count, 1)
    T.eq(f.toggle_count, 0)
    T.eq(m:is_holding(), false)
end)
T.test("M8 restore_on_release=0 keeps the dragged speed", function()
    local m, f = machine({ restore_on_release = 0 }, { speed = 1.0, x = 100 })
    m:on_down(0); m:on_tick(0.30)
    f.x = 300; m:on_tick(0.40)
    local before = f.set_speed_count
    m:on_up(0.50)
    T.near(f.speed, 3.0)
    T.eq(f.set_speed_count, before, "no extra set_speed on release")
    T.eq(f.hide_count, 1)
end)
T.test("M9 unchanged dx across ticks does not re-issue set_speed", function()
    local m, f = machine()
    m:on_down(0); m:on_tick(0.30)
    local n = f.set_speed_count
    m:on_tick(0.32); m:on_tick(0.34); m:on_tick(0.36)
    T.eq(f.set_speed_count, n)
end)
T.test("M10 small jitter inside deadzone does not change speed", function()
    local m, f = machine(nil, { x = 500 })
    m:on_down(0); m:on_tick(0.30)
    local n = f.set_speed_count
    f.x = 505; m:on_tick(0.32)
    f.x = 496; m:on_tick(0.34)
    T.eq(f.set_speed_count, n)
    T.near(f.speed, 2.0)
end)
T.test("M11 up without down is a no-op", function()
    local m, f = machine()
    m:on_up(1.0)
    T.eq(f.toggle_count, 0); T.eq(f.set_speed_count, 0); T.eq(f.hide_count, 0)
end)
T.test("M12 tick after an early release never starts a hold", function()
    local m, f = machine()
    m:on_down(0); m:on_up(0.10); m:on_tick(0.50); m:on_tick(1.0)
    T.eq(f.set_speed_count, 0)
    T.eq(m:is_holding(), false)
end)
T.test("M13 tick without any press is a no-op", function()
    local m, f = machine()
    m:on_tick(5.0)
    T.eq(f.set_speed_count, 0); T.eq(f.show_count, 0)
end)
T.test("M14 file end during hold cleans up; following up does not toggle", function()
    local m, f = machine(nil, { speed = 1.0 })
    m:on_down(0); m:on_tick(0.30)
    m:on_file_end()
    T.near(f.speed, 1.0); T.eq(f.hide_count, 1); T.eq(m:is_holding(), false)
    m:on_up(0.40)
    T.eq(f.toggle_count, 0)
end)
T.test("M15 release exactly at threshold with no tick in between counts as tap", function()
    local m, f = machine()
    m:on_down(0); m:on_up(0.25)
    T.eq(f.toggle_count, 1); T.eq(f.set_speed_count, 0)
end)
T.test("M16 threshold boundary: tick at exactly threshold starts the hold", function()
    local m, f = machine()
    m:on_down(0); m:on_tick(0.25)
    T.eq(m:is_holding(), true)
end)
T.test("M17 second gesture after a full cycle starts clean from the new origin", function()
    local m, f = machine(nil, { x = 100, speed = 1.0 })
    m:on_down(0); m:on_tick(0.30); f.x = 300; m:on_tick(0.40); m:on_up(0.50)
    T.near(f.speed, 1.0)
    f.x = 900
    m:on_down(1.0); m:on_tick(1.30)
    T.near(f.speed, 2.0, 1e-9, "new hold starts at hold_speed, not offset by old origin")
    T.eq(f.last_show.dx, 0)
end)
T.test("M18 second down while already pressed is ignored (no origin reset)", function()
    local m, f = machine(nil, { x = 100 })
    m:on_down(0); m:on_tick(0.30); f.x = 180
    m:on_down(0.35); m:on_tick(0.40)
    T.near(f.speed, 2.4, 1e-9, "origin must stay at 100")
end)
T.test("M19 drag during the pre-threshold window does not pre-set the origin", function()
    -- Mouse moved before the hold was recognised; origin is where the hold begins.
    local m, f = machine(nil, { x = 100 })
    m:on_down(0); f.x = 400; m:on_tick(0.10); m:on_tick(0.30)
    T.near(f.speed, 2.0)
    T.eq(f.last_show.dx, 0)
end)


-- ---------------------------------------------------------------- review round 1
T.test("S14 snapped output is always a multiple of 0.1", function()
    for dx = -800, 800 do
        local s = G.speed_for_drag(dx, D)
        T.near(s * 10, math.floor(s * 10 + 0.5), 1e-6, "dx=" .. dx)
    end
end)
T.test("S15 slow-stage slope law with snap off: 20px further out is exactly 0.1 more", function()
    local o = G.options({ snap_tenths = 0 })
    for dx = 8, 130, 7 do   -- stays below 3.0x on the right and above 0.5x on the left
        T.near(G.speed_for_drag(dx + 20, o) - G.speed_for_drag(dx, o), 0.1, 1e-9, "dx=" .. dx)
        T.near(G.speed_for_drag(-dx - 20, o) - G.speed_for_drag(-dx, o), -0.1, 1e-9, "dx=-" .. dx)
    end
end)
T.test("S16 odd symmetry about the origin inside the slow stage", function()
    local o = G.options({ snap_tenths = 0 })
    for dx = 0, 150, 13 do
        T.near(G.speed_for_drag(dx, o) - 2.0, -(G.speed_for_drag(-dx, o) - 2.0), 1e-9, "dx=" .. dx)
    end
end)
T.test("O5 infinite values fall back to defaults", function()
    local o = G.options({ hold_threshold = 1 / 0, max_speed = 1 / 0, min_speed = -1 / 0 })
    T.eq(o.hold_threshold, D.hold_threshold)
    T.eq(o.max_speed, D.max_speed)
    T.eq(o.min_speed, D.min_speed)
end)
T.test("M20 cancel during hold restores speed, hides OSD, never toggles pause", function()
    local m, f = machine(nil, { speed = 1.5 })
    m:on_down(0); m:on_tick(0.3); f.x = f.x + 200; m:on_tick(0.4)
    m:on_cancel()
    T.eq(f.toggle_count, 0); T.near(f.speed, 1.5); T.eq(f.hide_count, 1); T.eq(m:is_holding(), false)
    m:on_up(0.5)
    T.eq(f.toggle_count, 0, "up after cancel is ignored")
end)
T.test("M21 cancel before threshold is neither tap nor hold", function()
    local m, f = machine()
    m:on_down(0); m:on_cancel(); m:on_tick(0.5)
    T.eq(f.toggle_count, 0); T.eq(f.set_speed_count, 0); T.eq(m:is_holding(), false)
end)
T.test("M22 hold on a paused file leaves it playing after release (documented decision)", function()
    local m, f = machine(nil, { paused = true })
    m:on_down(0); m:on_tick(0.3); m:on_up(0.4)
    T.eq(f.paused, false); T.eq(f.toggle_count, 0)
end)
T.test("M23 identical ticks do not redraw the OSD; a dx change does", function()
    local m, f = machine(nil, { x = 500 })
    m:on_down(0); m:on_tick(0.3)
    local n = f.show_count
    m:on_tick(0.32); m:on_tick(0.34); m:on_tick(0.36)
    T.eq(f.show_count, n, "no redraw while nothing changed")
    f.x = 505; m:on_tick(0.38)
    T.eq(f.show_count, n + 1, "px read-out refreshes even inside the deadzone")
    T.near(f.speed, 2.0)
end)
T.test("M24 hold_threshold=0 starts the hold on the first tick", function()
    local m, f = machine({ hold_threshold = 0 })
    m:on_down(0); m:on_tick(0)
    T.eq(m:is_holding(), true)
end)
T.test("M25 file end with no press is a no-op", function()
    local m, f = machine()
    m:on_file_end()
    T.eq(f.hide_count, 0); T.eq(f.set_speed_count, 0)
end)
T.test("M26 round trip: release restores the start speed for any drag and any start speed", function()
    for _, s0 in ipairs({ 0.5, 1.0, 1.75, 3.0 }) do
        for _, dx in ipairs({ -1000, -100, 0, 37, 250, 2000 }) do
            local m, f = machine(nil, { speed = s0, x = 1000 })
            m:on_down(0); m:on_tick(0.3); f.x = 1000 + dx; m:on_tick(0.4); m:on_up(0.5)
            T.near(f.speed, s0, 1e-9, "s0=" .. s0 .. " dx=" .. dx)
        end
    end
end)
T.test("M27 origin comes from the first available mouse sample, not from 0", function()
    local m, f = machine(nil, { x = 500 })
    f.x = nil
    m:on_down(0); m:on_tick(0.3)
    T.near(f.speed, 2.0)
    f.x = 800; m:on_tick(0.35)
    T.near(f.speed, 2.0, 1e-9, "first sample becomes the origin")
    f.x = 880; m:on_tick(0.40)
    T.near(f.speed, 2.4)
end)


-- ---------------------------------------------------------------- two-stage curve (user feedback 2026-10-17)
T.test("S17 curve is continuous at the boost point: 208px = 3.0, next 10px = 3.1", function()
    T.near(G.speed_for_drag(208, D), 3.0)
    T.near(G.speed_for_drag(218, D), 3.1)
    local o = G.options({ snap_tenths = 0 })
    T.near(G.speed_for_drag(208, o), 3.0)
    T.near(G.speed_for_drag(209, o), 3.01)
end)
T.test("S18 fast-stage slope law with snap off: 10px further out is exactly 0.1 more", function()
    local o = G.options({ snap_tenths = 0 })
    for dx = 208, 490, 6 do
        T.near(G.speed_for_drag(dx + 10, o) - G.speed_for_drag(dx, o), 0.1, 1e-9, "dx=" .. dx)
    end
end)
T.test("S19 6.0 is reached at 8 + 200 + 300 = 508px and not before", function()
    local o = G.options({ snap_tenths = 0 })
    T.truthy(G.speed_for_drag(507, o) < 6.0, "507px already 6.0")
    T.near(G.speed_for_drag(508, o), 6.0)
    T.near(G.speed_for_drag(800, o), 6.0)
    T.near(G.speed_for_drag(508, D), 6.0)
end)
T.test("S20 halfway to the old 3.0 distance now gives 3.0 (user: distance halved)", function()
    T.near(G.speed_for_drag(8 + 200, D), 3.0)
end)
T.test("S21 left side is unaffected by the boost stage", function()
    local o = G.options({ snap_tenths = 0 })
    T.near(G.speed_for_drag(-108, o), 1.5)
    T.near(G.speed_for_drag(-308, o), 0.5)
end)
T.test("O6 boost_from_speed outside [hold_speed, max_speed] disables the fast stage", function()
    local o = G.options({ boost_from_speed = 9.0, snap_tenths = 0 })
    T.near(o.boost_from_speed, D.max_speed)
    T.near(G.speed_for_drag(308, o), 3.5)          -- still slow slope past 3.0
    local o2 = G.options({ boost_from_speed = 1.0, snap_tenths = 0 })
    T.near(o2.boost_from_speed, D.max_speed)
end)
T.test("O7 px_per_tenth_fast <= 0 falls back to default", function()
    local o = G.options({ px_per_tenth_fast = 0 })
    T.eq(o.px_per_tenth_fast, D.px_per_tenth_fast)
    T.near(G.speed_for_drag(218, o), 3.1)
end)
T.test("O8 boost_from_speed equal to hold_speed means fast slope from the start", function()
    local o = G.options({ boost_from_speed = 2.0, snap_tenths = 0 })
    T.near(G.speed_for_drag(18, o), 2.1)
end)

