T.test("A10 canceled up before threshold: no cycle pause, timer stopped", function()
    local mp = boot()
    mp.press("MBTN_LEFT", "down"); mp.time = 0.1; mp.fire_timers()
    mp.press("MBTN_LEFT", "up", true)
    T.eq(#mp.commands, 0); T.eq(mp.live_timers(), 0)
end)
T.test("A11 canceled up during hold restores speed and hides overlay", function()
    local mp = boot(nil, { speed = 1.5 })
    mp.press("MBTN_LEFT", "down"); mp.time = 0.3; mp.fire_timers()
    mp.props["mouse-pos"].x = 700; mp.fire_timers()
    mp.press("MBTN_LEFT", "up", true)
    T.near(mp.props.speed, 1.5); T.eq(mp.overlays[1].visible, false); T.eq(#mp.commands, 0)
end)
T.test("A12 MBTN_LEFT_DBL is swallowed so double-tap does not toggle fullscreen", function()
    local mp = boot()
    local b = mp.bindings["MBTN_LEFT_DBL"]
    T.truthy(b, "no binding for MBTN_LEFT_DBL")
    b.fn({ event = "press", key_name = "MBTN_LEFT_DBL" })
    T.eq(#mp.commands, 0); T.near(mp.props.speed, 1.0)
end)
T.test("A13 mouse-pos appearing mid-hold becomes the origin", function()
    local mp = boot()
    mp.props["mouse-pos"] = nil
    mp.press("MBTN_LEFT", "down"); mp.time = 0.3; mp.fire_timers()
    mp.props["mouse-pos"] = { x = 800, y = 10, hover = true }; mp.fire_timers()
    T.near(mp.props.speed, 2.0)
    mp.props["mouse-pos"].x = 880; mp.fire_timers()
    T.near(mp.props.speed, 2.4)
end)
T.test("A14 two downs without an up leave exactly one live timer", function()
    local mp = boot()
    mp.press("MBTN_LEFT", "down"); mp.press("MBTN_LEFT", "down")
    T.eq(mp.live_timers(), 1)
end)
T.test("A15 hidpi: mouse-pos is divided by display-hidpi-scale so 20 points stay 0.1x", function()
    local mp = boot(nil, { ["display-hidpi-scale"] = 2 })
    mp.press("MBTN_LEFT", "down"); mp.time = 0.3; mp.fire_timers()
    mp.props["mouse-pos"].x = 500 + 160; mp.fire_timers()   -- 160 backing px = 80 pt
    T.near(mp.props.speed, 2.4)
end)
T.test("A16 bare press event (no down/up) acts as a tap", function()
    local mp = boot()
    mp.press("MBTN_LEFT", "press")
    T.eq(#mp.commands, 1); T.eq(mp.commands[1][2], "pause"); T.eq(mp.live_timers(), 0)
end)

