package.path = "./?.lua;" .. package.path
local T = require "minitest"
local Fake = require "fake_mp"
local SCRIPT_DIR = assert(os.getenv("VT_SCRIPT_DIR"), "run via tests/run.sh (sets VT_SCRIPT_DIR)")

local function boot(opts, props)
    local mp, options = Fake.new()
    for k, v in pairs(opts or {}) do mp.option_overrides[k] = v end
    for k, v in pairs(props or {}) do mp.props[k] = v end
    Fake.load_adapter(mp, options, SCRIPT_DIR)
    return mp
end

T.test("A1 loading registers a complex forced binding on MBTN_LEFT and an end-file hook", function()
    local mp = boot()
    local b = mp.bindings["MBTN_LEFT"]
    T.truthy(b, "binding missing")
    T.eq(b.flags.complex, true)
    T.truthy(mp.events["end-file"], "end-file handler missing")
    T.eq(#mp.overlays, 1, "one OSD overlay created at load")
end)

T.test("A2 press, wait past threshold, tick: speed 2.0, unpaused, overlay drawn", function()
    local mp = boot(nil, { pause = true })
    mp.press("MBTN_LEFT", "down")
    T.eq(mp.live_timers(), 1, "poll timer started on down")
    mp.time = 0.3; mp.fire_timers()
    T.near(mp.props.speed, 2.0)
    T.eq(mp.props.pause, false)
    T.truthy(mp.overlays[1].visible)
    T.truthy(mp.overlays[1].data:find("2.0x", 1, true), "OSD text shows 2.0x: " .. mp.overlays[1].data)
end)

T.test("A3 drag right 80px while holding gives 2.4 and shows +80px", function()
    local mp = boot()
    mp.press("MBTN_LEFT", "down"); mp.time = 0.3; mp.fire_timers()
    mp.props["mouse-pos"].x = 580; mp.time = 0.35; mp.fire_timers()
    T.near(mp.props.speed, 2.4)
    T.truthy(mp.overlays[1].data:find("+80px", 1, true), mp.overlays[1].data)
end)

T.test("A4 release restores speed, removes overlay, kills the poll timer, shows a brief OSD", function()
    local mp = boot(nil, { speed = 1.5 })
    mp.press("MBTN_LEFT", "down"); mp.time = 0.3; mp.fire_timers()
    mp.props["mouse-pos"].x = 700; mp.time = 0.4; mp.fire_timers()
    mp.press("MBTN_LEFT", "up")
    T.near(mp.props.speed, 1.5)
    T.eq(mp.overlays[1].visible, false)
    T.eq(mp.live_timers(), 0)
    T.eq(#mp.osd_messages, 1)
    T.truthy(mp.osd_messages[1][1]:find("1.5x", 1, true), mp.osd_messages[1][1])
    T.eq(#mp.commands, 0, "no pause toggle on a hold")
end)

T.test("A5 tap sends `cycle pause`, leaves speed alone, kills timer, no OSD message", function()
    local mp = boot()
    mp.press("MBTN_LEFT", "down"); mp.time = 0.1; mp.fire_timers()
    mp.press("MBTN_LEFT", "up")
    T.eq(#mp.commands, 1)
    T.eq(mp.commands[1][1], "cycle"); T.eq(mp.commands[1][2], "pause")
    T.near(mp.props.speed, 1.0)
    T.eq(mp.live_timers(), 0)
    T.eq(#mp.osd_messages, 0)
end)

T.test("A6 script-opts values flow through: px_per_tenth=10 makes 48px = +0.4", function()
    local mp = boot({ px_per_tenth = 10 })
    mp.press("MBTN_LEFT", "down"); mp.time = 0.3; mp.fire_timers()
    mp.props["mouse-pos"].x = 548; mp.fire_timers()
    T.near(mp.props.speed, 2.4)
end)

T.test("A7 invalid script-opts (px_per_tenth=0) do not crash and fall back to default", function()
    local mp = boot({ px_per_tenth = 0 })
    mp.press("MBTN_LEFT", "down"); mp.time = 0.3; mp.fire_timers()
    mp.props["mouse-pos"].x = 548; mp.fire_timers()
    T.near(mp.props.speed, 2.2)
end)

T.test("A8 end-file during a hold restores speed and stops the timer", function()
    local mp = boot()
    mp.press("MBTN_LEFT", "down"); mp.time = 0.3; mp.fire_timers()
    mp.events["end-file"]({ event = "end-file" })
    T.near(mp.props.speed, 1.0)
    T.eq(mp.live_timers(), 0)
    T.eq(mp.overlays[1].visible, false)
end)

T.test("A9 mouse-pos unavailable (nil) does not crash; hold still reaches hold_speed", function()
    local mp = boot()
    mp.props["mouse-pos"] = nil
    mp.press("MBTN_LEFT", "down"); mp.time = 0.3; mp.fire_timers(); mp.fire_timers()
    T.near(mp.props.speed, 2.0)
end)


